class PermissionBasis(StrEnum):
    """Why we are allowed to hold the data (recorded on every source)."""

    OPERATOR_PROVIDED = "operator_provided"  # uploaded export you own/control
    FIRST_PARTY_ANALYTICS = "first_party_analytics"  # your own storefront
    OFFICIAL_API_TOS = "official_api_tos"  # official API under its ToS
    PERMISSIVE_LICENSE = "permissive_license"  # CC0/MIT/OWL etc.
    SYNTHETIC = "synthetic"  # generated by us, no third-party rights
    PUBLIC_DOMAIN = "public_domain"


ALLOWED_PERMISSION_BASES = {str(p) for p in PermissionBasis}


