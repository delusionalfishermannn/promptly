"""Shared vocabulary: statuses, enums and policy constants.

Kept free of imports from ``db``/``backend`` so every layer can depend on it.
Stored as plain strings in the DB (portable across SQLite/Postgres); Pydantic
validates the values at the API boundary.
"""

